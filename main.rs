#[repr(C, packed)]
pub struct gdt_ptr {
    pub limit: u16,
    pub base: u64,
}
pub fn load_gdt() {
    let pointer = gdt_ptr {
        limit: 23,
        base: &raw const GDT_DATA as u64,
    };
    unsafe {
        asm!(
            "lgdt [{0}]",
            "mov ax, 0x10",
            "mov ds, ax",
            "mov es, ax",
            "mov fs, ax",
            "mov gs, ax",
            "mov ss, ax",
            "push 0x08",
            "lea rax, [rip + 2f]",
            "push rax",
            "retfq",
            "2:",
            in(reg) &pointer
        );
    }
}

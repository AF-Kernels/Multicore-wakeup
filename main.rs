pub unsafe fn convert_str(mut num: u64, buf: &mut [u8; 20]) -> &str {
    let mut i = 20;
    loop {
        i -= 1;
        buf[i] = b'0' + (num % 10) as u8;
        num /= 10;
        if num == 0 {
            break;
        }
    }
    unsafe { core::str::from_utf8_unchecked(&buf[i..]) }
}
pub unsafe fn pc_speaker() {
    unsafe {
        let pit_command_port: u16 = 0x43;
        let pit_channel_data: u16 = 0x42;
        let system_control_port: u16 = 0x61;
        asm!("out dx, al", in("dx") pit_command_port, in("al") 0xB6 as u8);
        let divisor: u16 = 4000;
        let divisor_u8 = divisor as u8;
        asm!("out dx, al", in("dx") pit_channel_data, in("al") divisor_u8);
        let divisor_bit_8 = (divisor >> 8) as u8;
        asm!("out dx, al", in("dx") pit_channel_data, in("al") divisor_bit_8);
        let mut current_status: u8 = 0;
        asm!("in al, dx", in("dx") system_control_port, out("al") current_status);
        let new_status = current_status | 3;
        asm!("out dx, al", in("dx") system_control_port, in("al") new_status);
    }
}
pub fn apic_write(offset: usize, value: usize) {
    unsafe {
        let base_address = APIC_BASE as *mut u8;
        let final_address = (base_address.wrapping_add(offset)) as *mut u32;
        let _write = core::ptr::write_volatile(final_address, value as u32);
    }
}
pub fn print_screen(
    fb: *mut u32,
    stride: usize,
    screen_with_x: usize,
    screen_height_y: usize,
    color: u32,
    text: &str,
) {
    unsafe {
        let mut starting_position = screen_with_x;
        for c in text.bytes() {
            if (c as usize) >= FONT_BITMAPS.len() {
                continue;
            }
            let map = FONT_BITMAPS[c as usize];
            for row in 0..8 {
                for col in 0..8 {
                    if (map[row] >> (7 - col)) & 1 == 1 {
                        *fb.add((screen_height_y + row) * stride + (starting_position + col)) =
                            color;
                    }
                }
            }
            starting_position += 10;
        }
    }
}
pub extern "C" fn core_1_assembly_write() {
    unsafe {
        let tempoline_code_addr: *mut u8 = 0x8000 as *mut u8;
        let raw_addr = TRAMPOLINE_BIN.as_ptr();
        core::ptr::copy_nonoverlapping(raw_addr, tempoline_code_addr, TRAMPOLINE_BIN.len());
    }
}
pub extern "C" fn active_core(core_apic_id: u64) {
    unsafe {
        apic_write(0x310 as usize, (core_apic_id << 24) as usize);
        apic_write(0x300 as usize, 0x00004500 as usize);
        for _ in 0..20_000_000_u64 {
            asm!("pause");
        }
        apic_write(0x310 as usize, (core_apic_id << 24) as usize);
        apic_write(0x300 as usize, (0x00004600 | 0x08) as usize);
    }
}

#[repr(C, packed)]
pub struct FileHeader {
    pub file_name: [u8; 32],
    pub file_content: [u8; 32],
}
#[allow(static_mut_refs)]
pub extern "C" fn file_creation() {
    let file_data = b"Author: Arshman Farhan";
    let mut header = FileHeader {
        file_name: [0; 32],
        file_content: [0; 32],
    };
    let file_name_bytes = b"Author.txt";
    unsafe {
        let file_name_ptr = (&mut header.file_name as *mut [u8; 32]) as *mut [u8; 10];
        core::ptr::copy_nonoverlapping(file_name_bytes, file_name_ptr, 1);
        let file_data_ptr = (&mut header.file_content as *mut [u8; 32]) as *mut [u8; 22];
        core::ptr::copy_nonoverlapping(file_data, file_data_ptr, 1);
        let ram_disk_ptr = RAM_DISK.as_mut_ptr();
        let header_ptr = (&mut header as *mut FileHeader).cast::<u32>();
        let header_len = core::mem::size_of::<FileHeader>();
        core::ptr::copy_nonoverlapping(header_ptr, ram_disk_ptr, header_len);
    }
}
